package sunspec

import "strings"

func projectStorage(model DecodedModel) (capabilityProjection, bool) {
	return projectCapabilityPoints(model, "", "", func(point Fact) (string, string, MeterSignConvention) {
		if !strings.HasPrefix(point.FieldID, "storage.") {
			return "", "", ""
		}
		return point.FieldID, strings.TrimSpace(point.Unit), ""
	})
}

